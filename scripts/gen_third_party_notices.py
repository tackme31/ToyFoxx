BANNER = "=" * 79
RULE = "-" * 79


def read_text(path: Path) -> str:
    """Normalize to LF and a single trailing newline so output is byte-stable
    regardless of how git checked the input out."""
    raw = path.read_text(encoding="utf-8", errors="replace")
    return raw.replace("\r\n", "\n").replace("\r", "\n").rstrip("\n") + "\n"


def qwindowkit_version() -> str:
    """The submodule is pinned to a release tag; read it rather than repeat it,
    so a submodule bump makes --check fail until the notices are regenerated."""
    result = subprocess.run(
        ["git", "-C", str(REPO_ROOT / "third_party/qwindowkit"), "describe", "--tags", "--exact-match"],
        capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit("error: third_party/qwindowkit is not checked out at a release tag")
    return result.stdout.strip()


def components() -> list[dict]:
    licenses = REPO_ROOT / "licenses"
    return [
        {
            "name": "Qt",
            "version": QT_VERSION,
            "license": "LGPL-3.0-only",
            "homepage": "https://www.qt.io/",
            # LGPLv3 is written as additional permissions on top of GPLv3, so both texts travel.
            "text": "\n".join([QT_NOTICE, RULE, read_text(licenses / "LGPL-3.0.txt"),
                               RULE, read_text(licenses / "GPL-3.0.txt")]),
        },
        {
            "name": "FFmpeg",
            "version": FFMPEG_VERSION,
            "license": "LGPL-2.1-or-later",
            "homepage": "https://ffmpeg.org/",
            "text": "\n".join([FFMPEG_NOTICE, RULE, read_text(licenses / "LGPL-2.1.txt")]),
        },
        {
            "name": "QWindowKit",
            "version": qwindowkit_version(),
            "license": "Apache-2.0",
            "homepage": "https://github.com/stdware/qwindowkit",
            "text": "\n".join([QWINDOWKIT_NOTICE,
                               read_text(REPO_ROOT / "third_party/qwindowkit/LICENSE")]),
        },
    ]


def render() -> str:
    items = components()
    parts = [PREAMBLE, "Components", RULE]
    parts += [f"  {c['name']} {c['version']}  ({c['license']})" for c in items]
    parts.append("")
    for c in items:
        parts += [BANNER, f"{c['name']} {c['version']}", f"License: {c['license']}",
                  f"Homepage: {c['homepage']}", BANNER, "", c["text"]]
    return "\n".join(parts).rstrip("\n") + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the committed file is stale")
    args = parser.parse_args()

    out = REPO_ROOT / OUTPUT
    text = render()
    if args.check:
        current = out.read_text(encoding="utf-8") if out.exists() else ""
        if current != text:
            print(f"{OUTPUT} is stale; run python scripts/gen_third_party_notices.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT} is up to date")
        return 0
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
