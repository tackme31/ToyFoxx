"""Regenerate THIRD-PARTY-NOTICES.txt.

Usage:
    python scripts/gen_third_party_notices.py
    python scripts/gen_third_party_notices.py --check    # non-zero if stale

Run it after bumping Qt (update QT_VERSION and FFMPEG_VERSION below) or the
QWindowKit submodule. The output is committed and shipped in the release zip
next to LICENSE. Adapted from MegaDirStat's script of the same name.
"""

